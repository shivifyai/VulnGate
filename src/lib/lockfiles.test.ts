import { describe, expect, it } from 'vitest'
import type { Finding, RunResult } from '../types'
import { riskScore } from './exploits'
import { parseManifest, pickManifests } from './manifests'
import { toMarkdown } from './report'
import { optionsFromQuery, optionsToQuery } from './shareLink'

const names = (path: string, content: string) =>
  parseManifest(path, content).map((d) => `${d.name}@${d.version}${d.dev ? ' (dev)' : ''}`)

describe('more lockfiles', () => {
  it('yarn.lock v1', () => {
    const lock = `# THIS IS AN AUTOGENERATED FILE.
# yarn lockfile v1


"@babel/code-frame@^7.0.0", "@babel/code-frame@^7.10.4":
  version "7.12.13"
  resolved "https://registry.yarnpkg.com/@babel/code-frame/-/code-frame-7.12.13.tgz"
  dependencies:
    "@babel/highlight" "^7.12.13"

lodash@^4.17.15:
  version "4.17.20"
`
    expect(names('yarn.lock', lock)).toEqual(['@babel/code-frame@7.12.13', 'lodash@4.17.20'])
  })

  it('yarn.lock berry', () => {
    const lock = `__metadata:
  version: 6
  cacheKey: 8

"lodash@npm:^4.17.0":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"

"my-app@workspace:.":
  version: 0.0.0-use.local
  resolution: "my-app@workspace:."
`
    expect(names('yarn.lock', lock)).toEqual(['lodash@4.17.21'])
  })

  it('pnpm-lock.yaml v6 and v9', () => {
    const v6 = `lockfileVersion: '6.0'

packages:

  /@babel/core@7.22.0:
    resolution: {integrity: sha512-x}
    dev: true

  /react-dom@18.2.0(react@18.2.0):
    resolution: {integrity: sha512-y}
    dev: false
`
    expect(names('pnpm-lock.yaml', v6)).toEqual(['@babel/core@7.22.0 (dev)', 'react-dom@18.2.0'])

    const v9 = `lockfileVersion: '9.0'

importers:

  .:
    dependencies:
      lodash:
        specifier: ^4.17.0
        version: 4.17.21

packages:

  lodash@4.17.21:
    resolution: {integrity: sha512-z}

  '@types/node@20.1.0':
    resolution: {integrity: sha512-w}

snapshots:

  lodash@4.17.21: {}
`
    expect(names('pnpm-lock.yaml', v9)).toEqual(['lodash@4.17.21', '@types/node@20.1.0'])
  })

  it('Cargo.lock skips local crates', () => {
    const lock = `version = 3

[[package]]
name = "my-tool"
version = "0.1.0"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "1.0.150"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc"
`
    expect(names('Cargo.lock', lock)).toEqual(['serde@1.0.150'])
  })

  it('poetry.lock', () => {
    const lock = `[[package]]
name = "Django"
version = "3.2.0"
description = "web framework"
category = "main"

[package.dependencies]
asgiref = ">=3.3.2,<4"

[[package]]
name = "pytest"
version = "7.0.0"
category = "dev"

[metadata]
lock-version = "1.1"
`
    expect(names('poetry.lock', lock)).toEqual(['django@3.2.0', 'pytest@7.0.0 (dev)'])
  })

  it('Pipfile.lock', () => {
    const lock = JSON.stringify({
      default: { requests: { version: '==2.19.1' }, localpkg: { path: '.' } },
      develop: { pytest: { version: '==7.0.0' } },
    })
    expect(names('Pipfile.lock', lock)).toEqual(['requests@2.19.1', 'pytest@7.0.0 (dev)'])
  })

  it('Gemfile.lock only takes top-level specs', () => {
    const lock = `GIT
  remote: https://github.com/foo/bar.git
  specs:
    bar (0.1.0)

GEM
  remote: https://rubygems.org/
  specs:
    actionpack (6.1.0)
      rack (~> 2.0, >= 2.0.9)
    nokogiri (1.13.0-x86_64-linux)
      racc (~> 1.4)
    rack (2.2.3)

PLATFORMS
  x86_64-linux
`
    expect(names('Gemfile.lock', lock)).toEqual(['actionpack@6.1.0', 'nokogiri@1.13.0', 'rack@2.2.3'])
  })

  it('composer.lock', () => {
    const lock = JSON.stringify({
      packages: [{ name: 'guzzlehttp/guzzle', version: '7.4.0' }, { name: 'acme/thing', version: 'dev-main' }],
      'packages-dev': [{ name: 'phpunit/phpunit', version: 'v9.5.0' }],
    })
    expect(names('composer.lock', lock)).toEqual(['guzzlehttp/guzzle@7.4.0', 'phpunit/phpunit@9.5.0 (dev)'])
  })

  it('treats any npm lockfile as authoritative and skips fixtures', () => {
    expect(
      pickManifests([
        'package.json',
        'yarn.lock',
        'packages/web/package.json',
        'packages/web/pnpm-lock.yaml',
        '__fixtures__/old/package-lock.json',
        'src/testdata/go.mod',
        'rebuild/Cargo.lock',
      ]),
    ).toEqual(['packages/web/pnpm-lock.yaml', 'rebuild/Cargo.lock', 'yarn.lock'])
  })
})

const finding = (over: Partial<Finding>): Finding => ({
  key: over.id ?? 'x',
  id: 'GHSA-aaaa',
  aliases: [],
  summary: 'Something bad | with a pipe',
  details: '',
  severity: 'MEDIUM',
  dependency: { name: 'lodash', version: '4.17.20', ecosystem: 'npm', manifest: 'package-lock.json' },
  references: [],
  verdict: 'detected',
  ...over,
})

describe('risk ordering', () => {
  it('puts exploited bugs above higher-severity ones', () => {
    const exploitedMedium = finding({ severity: 'MEDIUM', kev: { dateAdded: '2024-01-01', ransomware: false } })
    const critical = finding({ severity: 'CRITICAL', score: 9.8 })
    const likelyHigh = finding({ severity: 'HIGH', epss: { score: 0.9, percentile: 0.99 } })
    const quietHigh = finding({ severity: 'HIGH', epss: { score: 0.001, percentile: 0.1 } })

    const sorted = [quietHigh, critical, likelyHigh, exploitedMedium].sort((a, b) => riskScore(b) - riskScore(a))
    expect(sorted).toEqual([exploitedMedium, critical, likelyHigh, quietHigh])
  })
})

describe('share links', () => {
  it('round-trips the options but never the token', () => {
    const query = optionsToQuery({
      repo: 'a/b', ref: 'v2', token: 'ghp_secret', failOn: 'CRITICAL', includeDev: true, failOnExploited: false,
    })
    expect(query).not.toContain('ghp_secret')
    expect(optionsFromQuery(query)).toEqual({
      repo: 'a/b', ref: 'v2', failOn: 'CRITICAL', includeDev: true, failOnExploited: false,
    })
    expect(optionsFromQuery('?nothing=here')).toBeNull()
  })
})

describe('markdown report', () => {
  it('summarises and escapes table cells', () => {
    const result: RunResult = {
      repo: { fullName: 'a/b', description: null, defaultBranch: 'main', stars: 0, htmlUrl: '', isPrivate: false },
      ref: 'main',
      manifests: ['package-lock.json'],
      dependencies: [],
      findings: [finding({ severity: 'HIGH', fixedIn: '4.17.21', kev: { dateAdded: '2024-01-01', ransomware: true } })],
      dependabotChecked: false,
      failOn: 'HIGH',
      failOnExploited: true,
      passed: false,
      finishedAt: '2026-01-01T00:00:00Z',
    }
    const md = toMarkdown(result)
    expect(md).toContain('❌ VulnGate failed: a/b@main')
    expect(md).toContain('Something bad \\| with a pipe')
    expect(md).toContain('🔥 exploited')
    expect(md).not.toContain('Dependabot |')
  })
})
