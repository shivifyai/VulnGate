function download(filename: string, content: string, type: string) {
  const url = URL.createObjectURL(new Blob([content], { type }))
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  a.click()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

const fileStem = (result: RunResult) => `vuln-report-${result.repo.fullName.replace('/', '-')}-${result.ref}`

export function downloadJson(result: RunResult) {
  download(`${fileStem(result)}.json`, JSON.stringify(result, null, 2), 'application/json')
}

export function downloadMarkdown(result: RunResult) {
  download(`${fileStem(result)}.md`, toMarkdown(result), 'text/markdown')
}

export function downloadCsv(result: RunResult) {
  download(`${fileStem(result)}.csv`, toCsv(result), 'text/csv')
}

export function toCsv(result: RunResult): string {
  const escape = (value: unknown) => {
    const text = String(value ?? '')
    return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text
  }

  const header = [
    'id', 'aliases', 'severity', 'score', 'package', 'ecosystem', 'version', 'fixed_in',
    'manifest', 'verdict', 'known_exploited', 'epss', 'summary',
  ]
  const rows = result.findings.map((f) => [
    f.id,
    f.aliases.join(' '),
    f.severity,
    f.score ?? '',
    f.dependency.name,
    f.dependency.ecosystem,
    f.dependency.version,
    f.fixedIn ?? '',
    f.dependency.manifest,
    f.verdict,
    f.kev ? 'yes' : '',
    f.epss?.score ?? '',
    f.summary,
  ])

  return [header, ...rows].map((row) => row.map(escape).join(',')).join('\n')
}

const SEVERITY_ICON = { CRITICAL: '🟥', HIGH: '🟧', MEDIUM: '🟨', LOW: '🟦', UNKNOWN: '⬜' }

// Pipes would break the table, newlines too
const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ')

/**
 * A report that reads well in a GitHub issue, PR comment or Actions job summary.
 * Long lists are capped so the comment doesn't blow past GitHub's size limit.
 */
export function toMarkdown(result: RunResult, { limit = 50 } = {}): string {
  const active = result.findings.filter((f) => f.verdict !== 'stale')
  const stale = result.findings.filter((f) => f.verdict === 'stale')
  const exploited = active.filter((f) => f.kev)

  const out: string[] = []
  out.push(`## ${result.passed ? '✅ VulnGate passed' : '❌ VulnGate failed'}: ${result.repo.fullName}@${result.ref}`)
  out.push('')

  const rule = `Gate: fail on **${result.failOn.toLowerCase()}** and above${result.failOnExploited ? ', or anything on CISA KEV' : ''}.`
  out.push(`Scanned **${result.dependencies.length}** packages from **${result.manifests.length}** manifests. ${rule}`)
  out.push('')

  out.push('| ' + SEVERITY_ORDER.map((s) => `${SEVERITY_ICON[s]} ${s.toLowerCase()}`).join(' | ') + ' | 🔥 exploited |')
  out.push('|' + ' --- |'.repeat(SEVERITY_ORDER.length + 1))
  out.push('| ' + SEVERITY_ORDER.map((s) => active.filter((f) => f.severity === s).length).join(' | ') + ` | ${exploited.length} |`)
  out.push('')

  if (active.length === 0) {
    out.push('No known vulnerabilities in the pinned versions. 🎉')
  } else {
    out.push('| Severity | Advisory | Package | Installed | Fixed in | Exploit risk |' + (result.dependabotChecked ? ' Dependabot |' : ''))
    out.push('| --- | --- | --- | --- | --- | --- |' + (result.dependabotChecked ? ' --- |' : ''))
    for (const f of active.slice(0, limit)) out.push(row(f, result.dependabotChecked))
    if (active.length > limit) {
      out.push('')
      out.push(`…and ${active.length - limit} more. Download the full JSON or CSV report for everything.`)
    }
  }

  if (stale.length) {
    out.push('')
    out.push(`<details><summary>${stale.length} Dependabot alerts look stale</summary>`)
    out.push('')
    for (const f of stale) out.push(`- [${f.id}](${f.alertUrl}): ${f.dependency.name} is at ${f.dependency.version}, which isn't affected`)
    out.push('')
    out.push('</details>')
  }

  out.push('')
  out.push(`<sub>Generated by VulnGate at ${new Date(result.finishedAt).toUTCString()}</sub>`)
  return out.join('\n')
}

function row(f: Finding, withVerdict: boolean) {
  const risk = [f.kev ? '🔥 exploited' : '', f.epss ? `EPSS ${formatEpss(f.epss.score)}` : ''].filter(Boolean).join(', ') || '—'
  const cols = [
    `${SEVERITY_ICON[f.severity]} ${f.severity.toLowerCase()}${f.score !== undefined ? ` ${f.score.toFixed(1)}` : ''}`,
    `[${f.id}](https://osv.dev/vulnerability/${f.id}) ${cell(f.summary)}`,
    `\`${f.dependency.name}\``,
    `\`${f.dependency.version}\``,
    f.fixedIn ? `\`${f.fixedIn}\`` : '—',
    risk,
  ]
  if (withVerdict) cols.push(VERDICT_LABELS[f.verdict].label)
  return `| ${cols.join(' | ')} |`
}
